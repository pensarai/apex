export const TriageOutcome = z.enum(["accept", "reject", "needs-info"]);
export type TriageOutcome = z.infer<typeof TriageOutcome>;

export const TriageReason = z.enum([
  "confirmed",
  "out-of-scope",
  "duplicate",
  "unreproducible",
  "informational",
  "business-accepted-risk",
  "missing-info",
]);
export type TriageReason = z.infer<typeof TriageReason>;

/**
 * Canonical HackerOne report state names. Maps onto the state machine
 * documented at https://docs.hackerone.com/en/articles/8475030-report-states.
 *
 * `null` is used for outcomes that do not have a clean H1 state mapping
 * (currently unused — every outcome maps to a state).
 */
export const HackerOneState = z.enum([
  "Triaged",
  "Needs More Info",
  "Duplicate",
  "Informative",
  "Not Applicable",
]);
export type HackerOneState = z.infer<typeof HackerOneState>;

export const TriageDecisionSchema = z.object({
  outcome: TriageOutcome,
  reason: TriageReason,
  rationale: z
    .string()
    .describe("One- to two-sentence explanation grounded in the signals"),
  suggestedHackerOneState: HackerOneState.nullable().describe(
    "Suggested H1 inbox state to transition the report to.",
  ),
  draftReplyMessage: z
    .string()
    .describe(
      "Paste-ready paragraph the engineer can post to the reporter when changing state.",
    ),
});
export type TriageDecision = z.infer<typeof TriageDecisionSchema>;

// ---------------------------------------------------------------------------
// Final emitted result
// ---------------------------------------------------------------------------

export const TriageResultSchema = z.object({
  schemaVersion: z.literal(1),
  reportPath: z.string(),
  target: z.string(),
  generatedAt: z.string().describe("ISO 8601 timestamp"),
  report: BountyReportSchema,
  scope: ScopeCheckResultSchema,
  duplicate: DupCheckResultSchema,
  verification: LiveVerificationResultSchema.nullable(),
  claimVerification: ClaimVerificationResultSchema.nullable(),
  cvss: CvssSummarySchema.nullable(),
  threatModelAlignment: ThreatModelAlignmentSchema.nullable(),
  decision: TriageDecisionSchema,
  remediation: PatchResultSchema.nullable(),
});
export type TriageResult = z.infer<typeof TriageResultSchema>;
